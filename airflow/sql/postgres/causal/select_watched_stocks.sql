-- 주간 인과 그래프의 대상이 되는 국내 관심종목.
--
-- **종목만 마스터에서 읽는다.** 지수 둘과 매크로 다섯은 `modules/causal/domain.py`의 상수다 —
-- 늘어나는 목록이 아니고, 늘리려면 후보 조립 SQL과 실현 등락 조회가 함께 바뀐다.
-- 반대로 종목은 관심종목을 늘리면 대상이 따라 늘어야 한다(저장소 규칙: 종목 코드를 코드에
-- 계속 추가하지 않는다).
--
-- 정렬은 `ticker`다. 대상 순서가 프롬프트 순서이므로 실행마다 흔들리면 안 된다.
-- `input_hash`는 정렬해서 접으므로 이 순서에 기대지 않는다.
-- **국내만이다.** 해외 상장 종목이 관심종목이 되면 KRX 거래일 축과 실현 등락 조회가
-- 달라져 이 흐름이 그대로 쓸 수 없다. 그때는 대상에 넣기 전에 그 조회부터 정한다.
SELECT ticker
FROM instrument
WHERE is_watched
  AND market IN ('kospi', 'kosdaq')
ORDER BY ticker
