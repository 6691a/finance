-- 그 주 대상 종목의 DART 공시. **임원 지분 신고는 뺀다.**
--
-- 점수로는 안 좁힌다. 공시에는 `value_score`에 해당하는 값이 없고 한 주에 종목당 열 건
-- 안팎이라 나머지는 전부 실어도 된다.
--
-- **다만 한 종류가 소음이다**(2026-08-28 실측). `임원ㆍ주요주주특정증권등소유상황보고서`가
-- 전체 3,850건 중 3,682건(**95퍼센트**)이고, 8/10 주 후보 22건 중 11건이 그것이었다.
-- 임원 하나가 주식을 사고팔 때마다 한 건이라 같은 회사 같은 날짜로 넷씩 쌓인다. 그 주
-- 주가를 움직인 원인이 아니고, 프로토타입 두 번에서 **공시 22건 중 인용이 한 건도 없었다.**
-- 후보 자리를 먹으면서 문서 쪽으로 가중치를 밀고 있었다.
--
-- **거르는 것은 이 하나뿐이다.** `조회공시요구`·`파생상품거래손실발생`·`반기보고서`처럼
-- 남는 것들은 실제로 사건이 될 수 있어 판단을 모델에 맡긴다. 목록을 늘리기 전에 인용률
-- (`cited`)을 보고 정한다 — 안 쓰이는 종류가 또 드러나면 그때 더한다.
--
-- 대상 종류 중 **종목만** 공시를 갖는다. 지수·환율·금리는 여기 안 걸린다.
--
-- `as_of_at` cutoff를 건다. 근거는 "그 시점에 알 수 있었던 것"이어야 한다.
SELECT stock_code,
       rcept_no,
       company_name,
       report_name,
       receipt_date
FROM disclosure_event
WHERE stock_code = ANY(%(codes)s)
  AND receipt_date BETWEEN %(week_start)s AND %(week_end)s
  AND detected_at < %(as_of_at)s
  -- `[기재정정]` 접두가 붙은 정정 공시도 같이 걸린다.
  AND report_name NOT LIKE '%%임원ㆍ주요주주특정증권등소유상황보고서%%'
ORDER BY receipt_date, rcept_no
