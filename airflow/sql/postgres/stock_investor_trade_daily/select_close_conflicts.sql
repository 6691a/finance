-- 들어온 확정 일봉과 이미 저장된 행의 종가가 어긋나는 거래일. **소급 조정 감지다.**
--
-- KIS는 수정주가를 준다. 액면분할·병합·증자가 있으면 그날 이후로 **과거 전체가 새 기준으로
-- 다시 쓰인다**(2026-08-26 실측: 2018-05-04 분할 뒤 2010-01-04 종가가 809,000이 아니라
-- 16,180으로 온다. 가격 나누기 50, 수량 곱하기 50, 금액 불변). `FID_ORG_ADJ_PRC`로 원주가를
-- 고를 수 없다 — 빈 값, 0, 1이 전부 같은 답을 준다.
--
-- 그래서 DB는 **받은 그 순간의 기준**으로 얼어 있고, 조정 뒤에 겹치는 30 거래일만 upsert되면
-- 한 종목 안에 두 기준이 섞인다. SMA60이 60봉 중 일부만 자릿수가 다른 값으로 계산된다.
--
-- **세로가 아니라 가로로 본다.** 날짜 간 급락은 진짜 폭락일 수 있어 조정과 가를 수 없다.
-- 여기서 보는 것은 **같은 거래일의 두 값**이다 — 과거는 변하지 않으므로 한 날짜의 종가가
-- 둘일 수 없고, 어긋났다면 소급 조정 말고는 설명이 없다. 확정된 행끼리는 그래서 오탐이 없다
-- (저장된 가장 최근 행은 아래에서 뺀다).
--
-- 종가 하나만 본다. 조정은 OHLC와 수량을 전부 바꾸므로 하나로 충분하다.
-- 비교는 numeric끼리라 자릿수 표기 차이(53000 대 53000.00)에 걸리지 않는다.
--
-- **저장된 가장 최근 행은 비교하지 않는다. 그 종가는 잠정값이다.** "과거는 변하지 않는다"는
-- 전제가 가장 최근 거래일에는 성립하지 않는다 — KIS는 그 행의 종가를 KRX 종가가 아니라 마지막
-- 체결가(NXT 애프터마켓 포함, 20:00까지)로 주고, 다음 거래일이 되어야 KRX 종가로 바꾼다.
-- 2026-09-18 실측: 000660의 09-18 저장값 1,847,000은 KRX 15:30 종가 1,857,000이 아니라
-- NXT 18:10 봉 1,846,000 쪽이었고, 이틀 뒤 일요일(09-20)에 받아도 NXT 19:59 봉 종가
-- 1,849,000이었다. 시각을 미뤄도 안 바뀌고 다음 거래일이 되어야 바뀐다.
-- 그 값이 저장돼 있다가 KRX 종가로 오면 어긋나고, 그것을 소급 조정으로 읽어 전 구간을
-- 재수집하다가 확인 재조회에서 또 값이 움직여 죽었다(2026-09-15부터 매일 재수집, 09-17·18
-- 실패). upsert가 다음 거래일에 확정값으로 덮으므로 비교에서 빼도 잃는 것이 없다.
--
-- **저장 시각이 아니라 위치로 가른다.** 처음에는 "자기 거래일 당일에 쓴 행"으로 갈랐는데,
-- 주말에 다시 받은 행은 쓴 날이 거래일이 아니어서 확정 행으로 읽혀 월요일에 오탐이 났다.
-- 가장 최근 행이 잠정이라는 사실은 언제 썼는지와 무관하다. 거래일이 이어지면 앞 행은 다음
-- 실행이 확정값으로 덮으며 넘어가고, 그 뒤에는 최근 행이 아니게 되어 다시 비교 대상이 된다.
--
-- 진짜 소급 조정은 분할일 이전 **전 기간**을 바꾸므로 가장 최근 행 하나를 빼도 나머지가 걸린다.
-- 겹치는 저장 행이 그 하나뿐이면 감지하지 못하지만, 종목당 30 거래일이 매일 겹쳐 들어오므로
-- 그런 상태는 첫 적재 직후뿐이다.
--
-- 판단은 DAG가 한다. 여기는 어긋난 거래일만 돌려준다.
SELECT stored.business_date
FROM stock_investor_trade_daily AS stored
JOIN unnest(%s::date[], %s::numeric[]) AS incoming(business_date, close_price)
  ON incoming.business_date = stored.business_date
WHERE stored.provider = 'kis'
  AND stored.stock_code = %s
  AND stored.business_date < (
      SELECT max(latest.business_date)
      FROM stock_investor_trade_daily AS latest
      WHERE latest.provider = stored.provider
        AND latest.stock_code = stored.stock_code
  )
  AND stored.close_price IS DISTINCT FROM incoming.close_price
ORDER BY stored.business_date
